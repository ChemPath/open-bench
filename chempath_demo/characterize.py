"""Per-compound structure characterization with open-source RDKit.

This is an open reference implementation of ChemPath's *output contract*:
each entry is resolved to a structure, characterized, and reported with an
explicit status. Formulation status is ``success`` when every entry is
characterized, ``partial`` when some are, and ``failed`` when none are.

The QC notes produced here are simple, illustrative checks written for this
demo. They are not the production ChemPath QC rules.
"""

from __future__ import annotations

import uuid
from collections import Counter
from datetime import datetime, timezone
from typing import Any, Optional

from rdkit import Chem, RDLogger, rdBase
from rdkit.Chem import Crippen, Descriptors, Lipinski, rdMolDescriptors

from chempath_demo import __version__
from chempath_demo.library import lookup
from chempath_demo.schema import (
    MAX_BATCH_ITEMS,
    Entry,
    RequestError,
    parse_formulation,
)

RDLogger.DisableLog("rdApp.*")

LABEL = "SYNTHETIC DEMO — not a laboratory result"

SCOPE: dict[str, list[str]] = {
    "covers": [
        "per-compound structure identity (canonical SMILES, InChI, InChIKey)",
        "molecular formula, molecular weight and exact mass",
        "standard RDKit physicochemical descriptors",
        "characterization coverage and input QC notes",
    ],
    "does_not_cover": [
        "measured or verified mixture composition",
        "synergy or compound-compound interaction",
        "efficacy, therapeutic benefit or dosing",
        "farm-to-patient traceability",
        "regulatory approval or suitability",
    ],
}

DISCLAIMER = (
    "Structure characterization only. Reported percentages are taken from the request "
    "and are not independently verified. This output does not establish synergy, "
    "efficacy, dosing, mixture composition or regulatory approval. Laboratory "
    "confirmation is required. Generated by the open ChemPath demo, not the "
    "production ChemPath engine."
)


def _now() -> str:
    """Current UTC time as an ISO-8601 string."""
    return datetime.now(timezone.utc).isoformat(timespec="seconds")


def _new_id(prefix: str) -> str:
    """Return a random, clearly demo-scoped identifier."""
    return f"{prefix}_{uuid.uuid4().hex[:12]}"


def _resolve(entry: Entry) -> tuple[Optional[Chem.Mol], str, Optional[str]]:
    """Resolve an entry to an RDKit molecule.

    Explicit structures take precedence over name lookup.

    Returns:
        ``(mol, source, reason)`` where ``mol`` is None when unresolved and
        ``reason`` explains why.
    """
    if entry.smiles:
        mol = Chem.MolFromSmiles(entry.smiles)
        return (mol, "smiles", None) if mol else (None, "smiles", "SMILES could not be parsed")
    if entry.inchi:
        mol = Chem.MolFromInchi(entry.inchi)
        return (mol, "inchi", None) if mol else (None, "inchi", "InChI could not be parsed")
    hit = lookup(entry.name)
    if hit is None:
        return None, "name", "name not in reference library; supply smiles or inchi"
    return Chem.MolFromSmiles(hit.smiles), "reference_library", None


def describe(mol: Chem.Mol) -> dict[str, Any]:
    """Compute identity fields and standard descriptors for a molecule."""
    return {
        "canonical_smiles": Chem.MolToSmiles(mol),
        "molecular_formula": rdMolDescriptors.CalcMolFormula(mol),
        "inchi": Chem.MolToInchi(mol),
        "inchikey": Chem.MolToInchiKey(mol),
        "molecular_weight": round(Descriptors.MolWt(mol), 3),
        "exact_mass": round(Descriptors.ExactMolWt(mol), 4),
        "descriptors": {
            "logp_crippen": round(Crippen.MolLogP(mol), 3),
            "tpsa": round(rdMolDescriptors.CalcTPSA(mol), 2),
            "h_bond_donors": Lipinski.NumHDonors(mol),
            "h_bond_acceptors": Lipinski.NumHAcceptors(mol),
            "rotatable_bonds": rdMolDescriptors.CalcNumRotatableBonds(mol),
            "heavy_atoms": mol.GetNumHeavyAtoms(),
            "ring_count": rdMolDescriptors.CalcNumRings(mol),
            "aromatic_rings": rdMolDescriptors.CalcNumAromaticRings(mol),
            "fraction_csp3": round(rdMolDescriptors.CalcFractionCSP3(mol), 3),
            "stereocenters": rdMolDescriptors.CalcNumAtomStereoCenters(mol),
        },
    }


def characterize_entry(entry: Entry) -> dict[str, Any]:
    """Characterize a single formulation entry.

    Returns:
        A result with ``status`` ``characterized`` or ``uncharacterizable``.
        Unresolved entries are reported with a reason, never dropped.
    """
    mol, source, reason = _resolve(entry)
    result: dict[str, Any] = {
        "input_name": entry.name,
        "reported_percentage": entry.percentage,
        "structure_source": source,
    }
    if mol is None:
        result.update(status="uncharacterizable", reason=reason)
        return result
    result.update(status="characterized", **describe(mol))
    return result


def _qc(results: list[dict[str, Any]]) -> dict[str, Any]:
    """Summarize coverage and flag simple input-consistency issues."""
    ok = [r for r in results if r["status"] == "characterized"]
    notes: list[str] = []

    reported = [r["reported_percentage"] for r in results if r["reported_percentage"] is not None]
    pct_sum = round(sum(reported), 4) if reported else None
    if pct_sum is not None:
        notes.append(f"reported percentages sum to {pct_sum}% (not independently verified)")
        if pct_sum > 100:
            notes.append("reported percentages exceed 100% in total")
    missing = len(results) - len(reported)
    if missing:
        notes.append(f"{missing} {'entry has' if missing == 1 else 'entries have'} no reported percentage")

    dupes = [k for k, n in Counter(r["inchikey"] for r in ok).items() if n > 1]
    if dupes:
        notes.append(f"same structure submitted more than once: {', '.join(dupes)}")
    unassigned = [r["input_name"] for r in ok if r["structure_source"] != "reference_library"
                  and r["descriptors"]["stereocenters"] and "@" not in r["canonical_smiles"]]
    if unassigned:
        notes.append(f"stereochemistry unspecified for: {', '.join(unassigned)}")

    return {
        "entries_submitted": len(results),
        "entries_characterized": len(ok),
        "coverage": round(len(ok) / len(results), 4),
        "reported_percentage_sum": pct_sum,
        "notes": notes,
    }


def analyze_formulation(payload: Any) -> dict[str, Any]:
    """Run a formulation analysis and return the JSON report.

    Args:
        payload: Formulation body; see :func:`chempath_demo.schema.parse_formulation`.

    Returns:
        A report dict. ``status`` is ``success``, ``partial`` or ``failed``.
        ``http_status`` gives the HTTP-style code for the outcome (422 when
        ``failed``), for wrapping the demo behind a web endpoint.

    Raises:
        RequestError: For malformed or invalid requests (400/422).
    """
    request = parse_formulation(payload)
    results = [characterize_entry(e) for e in request.entries]
    qc = _qc(results)
    n_ok = qc["entries_characterized"]
    status = "success" if n_ok == len(results) else "partial" if n_ok else "failed"
    return {
        "report_type": "Molecular Characterization Report",
        "label": LABEL,
        "analysis_id": _new_id("demo"),
        "created_at": _now(),
        "formulation_name": request.formulation_name,
        "status": status,
        "http_status": 422 if status == "failed" else 200,
        "entries": results,
        "qc": qc,
        "scope": SCOPE,
        "disclaimer": DISCLAIMER,
        "engine": {
            "name": "chempath-demo",
            "version": __version__,
            "rdkit_version": rdBase.rdkitVersion,
            "note": "Public demonstration build. Not the production ChemPath engine.",
        },
    }


def _run_item(item: Any) -> dict[str, Any]:
    """Run one batch item, converting request errors into a failed item."""
    if not isinstance(item, dict) or item.get("kind") not in ("formulation", "compound"):
        raise RequestError("item must be an object with kind 'formulation' or 'compound'", 400)
    if item["kind"] == "formulation":
        return analyze_formulation(item.get("formulation"))
    compound = item.get("compound")
    if not isinstance(compound, dict):
        raise RequestError("compound item requires a 'compound' object", 400)
    name = compound.get("name") or compound.get("smiles") or compound.get("inchi") or ""
    return analyze_formulation(
        {"formulation_name": f"compound: {name}", "entries": [{**compound, "name": name}]}
    )


def analyze_batch(payload: Any) -> dict[str, Any]:
    """Run up to 25 formulation or compound analyses.

    Every item is accounted for: valid items are analyzed, and invalid items
    are returned as ``failed`` with their error rather than failing the batch.

    Raises:
        RequestError: 400 if the body is not ``{"items": [...]}`` or exceeds
            the item limit.
    """
    if not isinstance(payload, dict) or not isinstance(payload.get("items"), list):
        raise RequestError("batch body must be an object with an 'items' list", 400)
    items = payload["items"]
    if not items or len(items) > MAX_BATCH_ITEMS:
        raise RequestError(f"batch must contain 1-{MAX_BATCH_ITEMS} items", 400)

    out: list[dict[str, Any]] = []
    for i, item in enumerate(items):
        try:
            report = _run_item(item)
            out.append({"index": i, "status": report["status"], "report": report})
        except RequestError as exc:
            out.append({"index": i, "status": "failed", "error": str(exc),
                        "http_status": exc.http_status})

    counts = Counter("failed" if o["status"] == "failed" else "succeeded" for o in out)
    status = ("success" if not counts["failed"]
              else "failed" if not counts["succeeded"] else "partial")
    return {
        "batch_id": _new_id("demobatch"),
        "label": LABEL,
        "created_at": _now(),
        "status": status,
        "items_submitted": len(out),
        "items_succeeded": counts["succeeded"],
        "items_failed": counts["failed"],
        "items": out,
    }
